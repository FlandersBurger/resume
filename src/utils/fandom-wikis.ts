/** Subcategories that are one franchise; a list's subject wins when both match. */
export const CATEGORY_WIKIS: Record<string, FandomWiki> = {
  "gaming.minecraft": SUBJECT_WIKIS["Minecraft"],
  "gaming.pokemon": SUBJECT_WIKIS["Pokémon"],
  "literature.harry_potter": SUBJECT_WIKIS["Harry Potter"],
  "literature.middle_earth": SUBJECT_WIKIS["Middle-Earth"],
  "movies.dc": { url: "https://dc.fandom.com", name: "DC Database" },
  "movies.marvel": SUBJECT_WIKIS["Marvel Cinematic Universe"],
  "movies.star_wars": SUBJECT_WIKIS["Star Wars"],
};

/** "Harry Potter" in "Harry Potter - Spells". */
export const listSubject = (name: string): string | undefined => name.match(/^(.*?\S)\s+[-–—]+\s+\S/)?.[1];

const bySubject = new Map(Object.entries(SUBJECT_WIKIS).map(([subject, wiki]) => [subject.toLowerCase(), wiki]));

/** The wiki to pull this list's pictures from, if one is assigned to its subject or a category. */
export const wikiFor = (list: { name: string; categories?: string[] }): FandomWiki | undefined => {
  const subject = listSubject(list.name);
  const wiki = subject && bySubject.get(subject.toLowerCase());
  if (wiki) return wiki;
  for (const category of list.categories ?? []) if (CATEGORY_WIKIS[category]) return CATEGORY_WIKIS[category];
  return undefined;
};
